package admin

import (
	"net/http"
	"time"

	"hatamoto.dev/core/internal/admin/ui"
	"hatamoto.dev/core/internal/adminpath"
	"hatamoto.dev/core/internal/httpx"
)

// securityAddressData is the read-only Security, Admin address page.
type securityAddressData struct {
	// Address is the full URL (site origin plus the admin address).
	Address  string
	Strength ui.Badge
	Reasons  []string
	// Chosen says who set the address and when.
	Chosen string
	// LockText replaces the Change button when the address cannot be changed here.
	LockText   string
	ChangeHref string
}

func (a *Admin) mountSecuritySettings(owner *httpx.Group) {
	owner.HandleFunc("GET /settings/security/admin-address", a.handleSecurityAddress)
	a.mountSecurityChange(owner)
	a.mountSecurityKeep(owner)
}

// fmtUTC is a moment as the Security page shows it: "25 Oct 2026, 14:02 UTC".
func fmtUTC(t time.Time) string { return t.UTC().Format("2 Jan 2006, 15:04") + " UTC" }

// addressChosen words who set the address. A nil time means the server made it
// at first start, or the install predates the record when the address is weak.
func addressChosen(st AddressState) string {
	if st.SetAt == nil {
		if st.Level == adminpath.LevelWeak {
			return "Not recorded"
		}
		return "Generated by the server at first start"
	}
	by := st.SetBy
	switch by {
	case "":
		return "Chosen on " + fmtUTC(*st.SetAt)
	case "cli":
		by = "the command line"
	}
	return "Chosen by " + by + " on " + fmtUTC(*st.SetAt)
}

// securityAddressView is the page data for the current address.
func (a *Admin) securityAddressView(r *http.Request, st AddressState) securityAddressData {
	// The cached level knows nothing of the site (its name, its pages); the
	// service assesses the live address with all of it.
	res := a.deps.Address.Assess(r.Context(), st.Path)
	st.Level, st.Reasons = res.Level, res.Reasons
	s := strengthOf(res)
	badge := ui.Badge{Label: s.Label, Kind: s.Kind, Wrap: true}
	if st.Level == adminpath.LevelWeak && st.AckAt != nil {
		badge.Label += " (accepted by " + st.AckBy + " on " + fmtDate(st.AckAt.UTC()) + ")"
	}
	d := securityAddressData{
		Address: a.addressOrigin(r) + st.Path, Strength: badge, Reasons: s.Reasons, Chosen: addressChosen(st),
	}
	if st.Lock != AddressUnlocked {
		d.LockText = addressLockText(st)
	} else {
		d.ChangeHref = a.url("settings", "security", "admin-address", "change")
	}
	return d
}

func (a *Admin) handleSecurityAddress(w http.ResponseWriter, r *http.Request) {
	if a.deps.Address == nil {
		a.unavailable(w, r, "Admin address")
		return
	}
	v := a.NewView(w, r, "Admin address")
	v.Section, v.Tab = "security", "admin-address"
	v.Width = "compact"
	v.Data = a.securityAddressView(r, a.deps.Address.State())
	a.Render(w, r, http.StatusOK, "settings/security-admin-address", v)
}
