const securityPath = "/admin/settings/security/admin-address"

func securityRig(t *testing.T, st AddressState) (*ownerRig, *fakeAddress) {
	t.Helper()
	g := newOwnerRig(t, true)
	fa := &fakeAddress{state: st}
	// By default the live assessment agrees with the cached state.
	fa.assess = func(path string) adminpath.Result {
		fa.mu.Lock()
		defer fa.mu.Unlock()
		return adminpath.Result{Path: path, Level: fa.state.Level, Reasons: fa.state.Reasons}
	}
	g.a.deps.Address = fa
	return g, fa
}

func chosenAt() *time.Time {
	t := time.Date(2026, time.October, 25, 14, 2, 0, 0, time.UTC)
	return &t
}

var strongState = AddressState{Path: "/k7qm-x2rf-9tdc", Level: adminpath.LevelStrong, SetBy: "Ana Ruiz", SetAt: chosenAt()}

func TestSecurityAddressPage(t *testing.T) {
	t.Parallel()

	g, _ := securityRig(t, strongState)
	rec := g.do("GET", securityPath, "owner-token", nil, nil)
	body := rec.Body.String()
	if rec.Code != 200 {
		t.Fatalf("%d", rec.Code)
	}
	for _, want := range []string{
		`value="https://acme.example/k7qm-x2rf-9tdc"`, `data-hm-copy-field="admin-address-url"`,
		"Strength:", ">strong<", "Chosen by Ana Ruiz on 25 Oct 2026, 14:02 UTC",
		`href="/admin/settings/security/admin-address/change"`, "Change address", "(asks for your password first)",
	} {
		if !strings.Contains(body, want) {
			t.Errorf("missing %q", want)
		}
	}
	if strings.ContainsAny(body, "\u2013\u2014") {
		t.Error("em or en dash on the page")
	}
	if issues := a11y.Check(body, a11y.Options{Page: true}); len(issues) > 0 {
		t.Errorf("a11y: %s", strings.Join(issues, "; "))
	}
	// A copy row inside .hm-setrow__text shrinks to the input's intrinsic width
	// and cuts the address off; it must sit directly in the list.
	if strings.Contains(body, `hm-setrow__text"><div class="hm-copyrow"`) || !strings.Contains(body, "<div class=\"hm-setlist\">\n<div class=\"hm-copyrow\">") {
		t.Error("the address copy row must be a direct child of .hm-setlist, not inside .hm-setrow__text")
	}
	compareGolden(t, "pages/settings-security-admin-address.html", normalizePage(body))
}

func TestSecurityAddressWeakReasonsAndAck(t *testing.T) {
	t.Parallel()

	weak := AddressState{Path: "/my-place", Level: adminpath.LevelWeak, SetBy: "Ana Ruiz", SetAt: chosenAt(),
		Reasons: []adminpath.Reason{{Code: "scanner", Text: "on the scanner list"}, {Code: "short", Text: "shorter than 10 characters"}}}
	g, fa := securityRig(t, weak)
	body := g.do("GET", securityPath, "owner-token", nil, nil).Body.String()
	for _, want := range []string{">weak<", "<li>on the list of addresses attack tools try</li>", "<li>shorter than 10 characters</li>"} {
		if !strings.Contains(body, want) {
			t.Errorf("unacknowledged weak: missing %q", want)
		}
	}
	if strings.Contains(body, "accepted by") {
		t.Error("no ack yet")
	}

	fa.mu.Lock()
	fa.state.AckBy, fa.state.AckAt = "Ana Ruiz", chosenAt()
	fa.mu.Unlock()
	body = g.do("GET", securityPath, "owner-token", nil, nil).Body.String()
	if !strings.Contains(body, "weak (accepted by Ana Ruiz on 25 Oct 2026)") {
		t.Errorf("accepted line missing:\n%s", body)
	}
	compareGolden(t, "pages/settings-security-admin-address-weak.html", normalizePage(body))
}

func TestSecurityAddressAssessesWithTheSite(t *testing.T) {
	t.Parallel()

	// The cached state says strong because it ignored the site name.
	cached := AddressState{Path: "/acme-co-portal", Level: adminpath.LevelStrong, SetBy: "Ana Ruiz", SetAt: chosenAt(), AckBy: "Ana Ruiz", AckAt: chosenAt()}
	g, fa := securityRig(t, cached)
	fa.assess = func(path string) adminpath.Result {
		return adminpath.Result{Path: path, Level: adminpath.LevelWeak, Reasons: []adminpath.Reason{{Code: "site-name", Text: "contains the site name"}}}
	}
	body := g.do("GET", securityPath, "owner-token", nil, nil).Body.String()
	for _, want := range []string{"weak (accepted by Ana Ruiz on 25 Oct 2026)", "<li>contains the site name</li>"} {
		if !strings.Contains(body, want) {
			t.Errorf("missing %q:\n%s", want, body)
		}
	}
}

func TestSecurityAddressChosenVariants(t *testing.T) {
	t.Parallel()

	for name, c := range map[string]struct {
		st   AddressState
		want string
	}{
		"by a person":       {strongState, "Chosen by Ana Ruiz on 25 Oct 2026, 14:02 UTC"},
		"by the CLI":        {AddressState{Path: "/k7qm-x2rf-9tdc", Level: adminpath.LevelStrong, SetBy: "cli", SetAt: chosenAt()}, "Chosen by the command line on 25 Oct 2026, 14:02 UTC"},
		"no name":           {AddressState{Path: "/k7qm-x2rf-9tdc", Level: adminpath.LevelStrong, SetAt: chosenAt()}, "Chosen on 25 Oct 2026, 14:02 UTC"},
		"generated at boot": {AddressState{Path: "/k7qm-x2rf-9tdc", Level: adminpath.LevelStrong}, "Generated by the server at first start"},
		"upgraded install":  {AddressState{Path: "/old-address", Level: adminpath.LevelWeak}, "Not recorded"},
	} {
		g, _ := securityRig(t, c.st)
		if body := g.do("GET", securityPath, "owner-token", nil, nil).Body.String(); !strings.Contains(body, c.want) {
			t.Errorf("%s: missing %q", name, c.want)
		}
	}
}

func TestSecurityAddressOwnerOnly(t *testing.T) {
	t.Parallel()

	g, _ := securityRig(t, strongState)
	if rec := g.do("GET", securityPath, "editor-token", nil, nil); rec.Code != 403 {
		t.Errorf("editor: %d", rec.Code)
	}
	if rec := g.do("GET", securityPath, "", nil, nil); rec.Code != 303 {
		t.Errorf("anonymous: %d", rec.Code)
	}
	if rec := g.do("GET", "/admin/settings/security", "owner-token", nil, nil); rec.Code != 302 || rec.Header().Get("Location") != securityPath {
		t.Errorf("section entry: %d %s", rec.Code, rec.Header().Get("Location"))
	}
	if rec := g.do("GET", "/admin/settings/security", "editor-token", nil, nil); rec.Code != 403 {
		t.Errorf("editor section entry: %d", rec.Code)
	}
}

func TestSecurityAddressLocked(t *testing.T) {
	t.Parallel()

	pinned := strongState
	pinned.Lock, pinned.Pinned = AddressLockedEnv, "HATAMOTO_ADMIN_PATH"
	g, _ := securityRig(t, pinned)
	body := g.do("GET", securityPath, "owner-token", nil, nil).Body.String()
	if !strings.Contains(body, "Set by the server environment (HATAMOTO_ADMIN_PATH).") || strings.Contains(body, "Change address") || strings.Contains(body, "/change") {
		t.Errorf("pinned page:\n%s", body)
	}
	compareGolden(t, "pages/settings-security-admin-address-pinned.html", normalizePage(body))

	demo := strongState
	demo.Lock = AddressLockedDemo
	g, _ = securityRig(t, demo)
	body = g.do("GET", securityPath, "owner-token", nil, nil).Body.String()
	if !strings.Contains(body, "Changing the address is turned off in the demo.") || strings.Contains(body, "Change address") {
		t.Error("demo page")
	}
}

