-- Comments: schema for core comments. Comments stay OFF: the settings row is
-- created with enabled = false on new and existing sites. No author URL and no
-- raw IP is stored anywhere (ip_hash / net_hash are HMACs). Expand only: new
-- tables the previous release never reads. Rollback floor: unchanged.

-- +goose Up
CREATE SEQUENCE IF NOT EXISTS hatamoto_comments_seq;

CREATE TABLE IF NOT EXISTS hatamoto_commenters (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    email_hash text NOT NULL UNIQUE,
    email_sealed bytea NOT NULL,
    trust_level text NOT NULL DEFAULT 'new' CHECK (trust_level IN ('new','known','trusted','blocked')),
    approved_count integer NOT NULL DEFAULT 0,
    first_approved_at timestamptz,
    last_spam_at timestamptz,
    token_version integer NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS hatamoto_comments (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    seq bigint NOT NULL UNIQUE DEFAULT nextval('hatamoto_comments_seq'),
    entity_id uuid NOT NULL REFERENCES hatamoto_entities(id) ON DELETE CASCADE,
    parent_id uuid REFERENCES hatamoto_comments(id) ON DELETE CASCADE,
    path text COLLATE "C" NOT NULL UNIQUE,
    depth smallint NOT NULL CHECK (depth BETWEEN 1 AND 32),
    status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','pending','approved','spam','trash')),
    body_raw text NOT NULL,
    body_html text NOT NULL,
    has_links boolean NOT NULL DEFAULT false,
    link_domains text[] NOT NULL DEFAULT '{}',
    body_hash text NOT NULL DEFAULT '',
    commenter_id uuid REFERENCES hatamoto_commenters(id) ON DELETE SET NULL,
    author_name text NOT NULL DEFAULT '' CHECK (char_length(author_name) <= 100),
    author_user_id uuid REFERENCES hatamoto_users(id) ON DELETE SET NULL,
    ip_hash text NOT NULL DEFAULT '',
    net_hash text NOT NULL DEFAULT '',
    user_agent text NOT NULL DEFAULT '' CHECK (char_length(user_agent) <= 256),
    spam_score integer NOT NULL DEFAULT 0,
    spam_verdict text NOT NULL DEFAULT 'allow' CHECK (spam_verdict IN ('allow','hold','spam')),
    spam_reasons jsonb NOT NULL DEFAULT '[]',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    confirmed_at timestamptz,
    approved_at timestamptz,
    approved_by uuid REFERENCES hatamoto_users(id) ON DELETE SET NULL,
    edited_at timestamptz,
    locale text NOT NULL DEFAULT ''
);
-- thread roots page, subtree range scan, moderation queue, per-commenter, duplicates
CREATE INDEX IF NOT EXISTS hatamoto_comments_roots_idx ON hatamoto_comments (entity_id, created_at DESC, seq DESC) WHERE parent_id IS NULL AND status = 'approved';
CREATE INDEX IF NOT EXISTS hatamoto_comments_entity_path_idx ON hatamoto_comments (entity_id, path);
CREATE INDEX IF NOT EXISTS hatamoto_comments_status_idx ON hatamoto_comments (status, created_at DESC);
CREATE INDEX IF NOT EXISTS hatamoto_comments_commenter_idx ON hatamoto_comments (commenter_id);
CREATE INDEX IF NOT EXISTS hatamoto_comments_body_hash_idx ON hatamoto_comments (body_hash, created_at) WHERE body_hash <> '';

CREATE TABLE IF NOT EXISTS hatamoto_comment_settings (
    id boolean PRIMARY KEY DEFAULT true CHECK (id),
    enabled boolean NOT NULL DEFAULT false,
    settings jsonb NOT NULL DEFAULT '{}',
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by uuid REFERENCES hatamoto_users(id) ON DELETE SET NULL
);
INSERT INTO hatamoto_comment_settings (id) VALUES (true) ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS hatamoto_comment_entities (
    entity_id uuid PRIMARY KEY REFERENCES hatamoto_entities(id) ON DELETE CASCADE,
    mode text CHECK (mode IN ('open','closed','hidden')),
    comment_count integer NOT NULL DEFAULT 0,
    pending_count integer NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS hatamoto_comment_blocks (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    kind text NOT NULL CHECK (kind IN ('email_domain','link_domain','ip_hash','net_hash','body_hash')),
    value text NOT NULL,
    source text NOT NULL DEFAULT 'manual' CHECK (source IN ('seed','manual','spam')),
    note text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by uuid REFERENCES hatamoto_users(id) ON DELETE SET NULL,
    UNIQUE (kind, value)
);
