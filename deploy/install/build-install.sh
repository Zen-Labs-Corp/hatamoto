#!/usr/bin/env bash
# build-install.sh - assemble install.sh and firstboot.sh from deploy/install/src.
#
#   install.sh   = src/common + generated key block + src/install + payloads
#   firstboot.sh = src/common + src/firstboot
#
# The trusted keys are generated from the key files, never typed in a part. The
# output is deterministic (no dates, no paths), so the hosted copy, the release
# asset and a local build of the same tag are the same bytes.
#
# Usage: build-install.sh [--keys-dir DIR] [--out DIR]
set -euo pipefail
export LC_ALL=C

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
keys_dir="$repo/backend/internal/release/keys"
out_dir="dist"

die() { echo "build-install: $*" >&2; exit 1; }

while [ $# -gt 0 ]; do
  case "$1" in
    --keys-dir) [ $# -ge 2 ] || die "--keys-dir needs a value"; keys_dir="$2"; shift 2 ;;
    --out) [ $# -ge 2 ] || die "--out needs a value"; out_dir="$2"; shift 2 ;;
    *) die "unknown argument: $1" ;;
  esac
done

command -v jq >/dev/null || die "jq is required"
command -v sha256sum >/dev/null || die "sha256sum is required"
[ -d "$keys_dir" ] || die "keys dir not found: $keys_dir"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# cat_parts prints every *.sh part of a directory in name order, each ending in
# a newline, except the one named by $2. A missing directory is fine: parts arrive in separate changes.
cat_parts() {
  local f
  [ -d "$1" ] || return 0
  for f in "$1"/*.sh; do
    [ -e "$f" ] || continue
    [ "$(basename "$f")" != "${2:-}" ] || continue
    cat "$f"
    [ -z "$(tail -c1 "$f")" ] || echo
  done
}

# key_block prints the two shell variables holding the trusted keys. Only *.pub
# files are keys (the Go loader embeds keys/*.pub); the file name picks the set
# exactly like backend/internal/release/trust.go.
key_block() {
  local f name set id pub raw rel="" man=""
  for f in "$keys_dir"/*.pub; do
    [ -e "$f" ] || continue
    name="$(basename "$f")"
    case "$name" in
      release-*.pub) set=release ;;
      manifest.pub | manifest-*.pub) set=manifest ;;
      *) die "unexpected key file name: $name" ;;
    esac
    id="$(jq -er '.key_id' "$f")" || die "$name: no key_id"
    pub="$(jq -er '.public' "$f")" || die "$name: no public key"
    [[ "$id" =~ ^[0-9a-f]{16}$ ]] || die "$name: bad key_id"
    [[ "$pub" =~ ^[A-Za-z0-9+/]+=*$ ]] || die "$name: bad public key"
    raw="$(printf '%s' "$pub" | base64 -d | sha256sum | cut -c1-16)"
    [ "$raw" = "$id" ] || die "$name: key_id does not match the key"
    if [ "$set" = release ]; then rel+="$id $pub"$'\n'; else man+="$id $pub"$'\n'; fi
  done
  [ -n "$rel" ] || die "no release keys in $keys_dir"
  [ -n "$man" ] || die "no manifest keys in $keys_dir"
  printf '\n# Generated by build-install.sh from the key files. Not editable.\n'
  printf "TRUSTED_MANIFEST_KEYS='%s'\n" "$man"
  printf "TRUSTED_RELEASE_KEYS='%s'\n" "$rel"
}

# payload prints a shell function that writes a file's exact bytes to stdout.
payload() {
  local fn="$1" file="$2" tag="$3"
  [ -f "$file" ] || die "payload source missing: $file"
  [ -z "$(tail -c1 "$file")" ] || die "payload does not end in a newline: $file"
  if grep -qx "$tag" "$file"; then die "payload contains its delimiter $tag: $file"; fi
  printf '\n%s() {\n' "$fn"
  printf "cat <<'%s'\n" "$tag"
  cat "$file"
  printf '%s\n}\n' "$tag"
}

# firstboot.sh first: install.sh embeds it.
{
  cat_parts "$here/src/common"
  cat_parts "$here/src/firstboot"
} > "$work/firstboot.sh"

# 90-main.sh is emitted after the payloads so that main "$@" is the last line.
[ -f "$here/src/install/90-main.sh" ] || die "src/install/90-main.sh is missing"
{
  cat_parts "$here/src/common"
  key_block
  cat_parts "$here/src/install" 90-main.sh
  payload payload_unit "$repo/deploy/systemd/hatamoto-api.service" HM_PAYLOAD_UNIT
  payload payload_install_unit "$repo/deploy/install-unit.sh" HM_PAYLOAD_INSTALL_UNIT
  payload payload_firstboot "$work/firstboot.sh" HM_PAYLOAD_FIRSTBOOT
  echo
  cat "$here/src/install/90-main.sh"
} > "$work/install.sh"

for f in install.sh firstboot.sh; do
  [ "$(tail -n1 "$work/$f")" = 'main "$@"' ] || die "$f does not end with main \"\$@\""
done

mkdir -p "$out_dir"
install -m 0755 "$work/install.sh" "$out_dir/install.sh"
install -m 0755 "$work/firstboot.sh" "$out_dir/firstboot.sh"
